-- Companies and Bikes schema contribution for the Smart Bike Rental database.
-- Naming follows the Milestone 2 convention: lowercase snake_case plural tables.

CREATE TABLE companies (
    company_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(50) NOT NULL,
    company_email VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE bikes (
    bike_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id INTEGER NOT NULL,
    qr_code VARCHAR(50) NOT NULL UNIQUE,
    status VARCHAR(50) NOT NULL,
    CONSTRAINT fk_bikes_company
        FOREIGN KEY (company_id)
        REFERENCES companies (company_id)
);
