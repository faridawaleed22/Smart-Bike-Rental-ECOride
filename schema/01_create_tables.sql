/* =========================
  CREATE TABLE
   ========================= */
CREATE TABLE riders (
    riderID             SERIAL PRIMARY KEY,
    FullName            VARCHAR(50)  NOT NULL,
    email               VARCHAR(100) NOT NULL UNIQUE,
    password            VARCHAR(255) NOT NULL,
    phonenumber         VARCHAR(11)  NOT NULL UNIQUE
                        CHECK (phonenumber ~ '^[0-9]{11}$'),
    VerificationStatus  BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE admins (
    adminID SERIAL PRIMARY KEY,
    fullName VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL

);

CREATE TABLE companies (
    companyID SERIAL PRIMARY KEY,
    companyName VARCHAR(50) NOT NULL,
    companyEmail VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE pricing_plans (
    pricingID SERIAL PRIMARY KEY,
    planType VARCHAR(50) NOT NULL UNIQUE,
    price DECIMAL(10,2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE stations (
    stationID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stationName VARCHAR(50) NOT NULL ,
    location VARCHAR(255) NOT NULL,
    dockCapacity INT NOT NULL CHECK (dockCapacity >= 0)
	
);

CREATE TABLE bikes (
    bikeID SERIAL PRIMARY KEY,
    companyID INT NOT NULL,
    QRCODE VARCHAR(50) NOT NULL UNIQUE,
   Status VARCHAR(50) NOT NULL
    CHECK (Status IN ('available', 'rented', 'maintenance', 'out_of_service')),
    CONSTRAINT fk_bikes_company
        FOREIGN KEY (companyID) REFERENCES companies(companyID)
	ON DELETE RESTRICT
);

CREATE TABLE docks (
    dockID SERIAL PRIMARY KEY,
    stationID INT NOT NULL,
    bikeID INT UNIQUE,
    status VARCHAR(50) NOT NULL DEFAULT 'available'
        CHECK (status IN ('available', 'occupied', 'out_of_service')),

    CONSTRAINT fk_dock_station
        FOREIGN KEY (stationID) REFERENCES stations(stationID)
        ON DELETE CASCADE,

    CONSTRAINT fk_dock_bike
        FOREIGN KEY (bikeID) REFERENCES bikes(bikeID)
        ON DELETE SET NULL


);

CREATE TABLE rentals (
    rentalID SERIAL PRIMARY KEY,

    riderID INT NOT NULL,
    bikeID INT NOT NULL,
    pricingID INT NOT NULL,

    startStationID INT NOT NULL,
    endStationID INT,

    startTime TIMESTAMP NOT NULL DEFAULT NOW(),
    endTime TIMESTAMP,

    usageDuration INT,

    status VARCHAR(20) NOT NULL DEFAULT 'active',

    totalCost DECIMAL(10,2),

    CONSTRAINT fk_rentals_rider
        FOREIGN KEY (riderID)
        REFERENCES riders(riderID)
        ON DELETE RESTRICT,

    CONSTRAINT fk_rentals_bike
        FOREIGN KEY (bikeID)
        REFERENCES bikes(bikeID)
        ON DELETE RESTRICT,

    CONSTRAINT fk_rentals_pricing
        FOREIGN KEY (pricingID)
        REFERENCES pricing_plans(pricingID)
        ON DELETE RESTRICT,

    CONSTRAINT fk_rentals_start_station
        FOREIGN KEY (startStationID)
        REFERENCES stations(stationID)
        ON DELETE RESTRICT,

    CONSTRAINT fk_rentals_end_station
        FOREIGN KEY (endStationID)
        REFERENCES stations(stationID)
        ON DELETE RESTRICT,

    CONSTRAINT chk_rental_status
        CHECK (status IN ('active', 'completed', 'cancelled')),

    CONSTRAINT chk_rental_time
        CHECK (endTime IS NULL OR endTime >= startTime),

    CONSTRAINT chk_usage_duration
        CHECK (usageDuration IS NULL OR usageDuration >= 0),

    CONSTRAINT chk_total_cost
        CHECK (totalCost IS NULL OR totalCost >= 0)
);

CREATE TABLE payments (
    paymentID SERIAL PRIMARY KEY,

    rentalID INT NOT NULL,

    amount DECIMAL(10,2) NOT NULL,

    paymentStatus VARCHAR(50) NOT NULL,

    paymentTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_payments_rental
        FOREIGN KEY (rentalID)
        REFERENCES rentals(rentalID)
        ON DELETE RESTRICT,

    CONSTRAINT chk_payment_amount
        CHECK (amount >= 0),

    CONSTRAINT chk_payment_status
        CHECK (paymentStatus IN ('Pending', 'Completed', 'Failed', 'Refunded'))
);

CREATE TABLE issues (
    issueID SERIAL PRIMARY KEY,

    riderID INT NOT NULL,
    bikeID INT NOT NULL,
    rentalID INT,
    handledByAdminID INT,

    issueType VARCHAR(50) NOT NULL,
    description TEXT,

    status VARCHAR(20) NOT NULL DEFAULT 'open',

    CONSTRAINT fk_issues_rider
        FOREIGN KEY (riderID)
        REFERENCES riders(riderID)
        ON DELETE RESTRICT,

    CONSTRAINT fk_issues_bike
        FOREIGN KEY (bikeID)
        REFERENCES bikes(bikeID)
        ON DELETE RESTRICT,

    CONSTRAINT fk_issues_rental
        FOREIGN KEY (rentalID)
        REFERENCES rentals(rentalID)
        ON DELETE SET NULL,

    CONSTRAINT fk_issues_admin
        FOREIGN KEY (handledByAdminID)
        REFERENCES admins(adminID)
        ON DELETE SET NULL,

    CONSTRAINT chk_issue_status
        CHECK (status IN ('open', 'in_progress', 'resolved'))
);

CREATE TABLE penalties (
    penaltyID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    riderID INT NOT NULL,
    adminID INT,

    accountAction VARCHAR(100) NOT NULL,
    reason TEXT NOT NULL,

    CONSTRAINT fk_penalties_rider
        FOREIGN KEY (riderID)
        REFERENCES riders(riderID)
        ON DELETE RESTRICT,

    CONSTRAINT fk_penalties_admin
        FOREIGN KEY (adminID)
        REFERENCES admins(adminID)
        ON DELETE SET NULL
);

CREATE TABLE notifications (
    notificationID  SERIAL PRIMARY KEY,

    riderID          INT NOT NULL
                      REFERENCES riders(riderID) ON DELETE CASCADE,
					  
    rentalID         INT NULL
                      REFERENCES rentals(rentalID) ON DELETE SET NULL,
    message           TEXT        NOT NULL,
    notificationTYPE VARCHAR(30) NOT NULL
                      CHECK (notificationTYPE IN
                             ('rental', 'payment', 'penalty', 'issue', 'general'))
);
