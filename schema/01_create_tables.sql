CREATE TABLE riders (
    riderID             SERIAL PRIMARY KEY,
    FullName            VARCHAR(50)  NOT NULL,
    email               VARCHAR(100) NOT NULL UNIQUE,
    password            VARCHAR(255) NOT NULL,
    phonenumber         VARCHAR(11)  NOT NULL UNIQUE
                        CHECK (phonenumber ~ '^[0-9]{11}$'),
    VerificationStatus  BOOLEAN      NOT NULL DEFAULT FALSE
);




CREATE TABLE notifications (
    notificationID  SERIAL PRIMARY KEY,

    riderID          INT NOT NULL
                      REFERENCES riders(riderID) ON DELETE CASCADE,
					  
    rentalID         INT NULL
                      REFERENCES rentals(rentalID) ON DELETE SET NULL,
    message           TEXT        NOT NULL,
    notificationTYPE VARCHAR(30) NOT NULL
                      CHECK (notificationTYPE IN
                             ('rental', 'payment', 'penalty', 'issue', 'general'))
);

CREATE TABLE admins (
    adminID SERIAL PRIMARY KEY,
    fullName VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL

);



CREATE TABLE pricing_plans (
    pricingID SERIAL PRIMARY KEY,
    planType VARCHAR(50) NOT NULL UNIQUE,
    price DECIMAL(10,2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE companies (
    companyID SERIAL PRIMARY KEY,
    companyName VARCHAR(50) NOT NULL,
    companyEmail VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE bikes (
    bikeID SERIAL PRIMARY KEY,
    companyID INT NOT NULL,
    QRCODE VARCHAR(50) NOT NULL UNIQUE,
    Status VARCHAR(50) NOT NULL,

    CONSTRAINT fk_bikes_company
        FOREIGN KEY (companyID) REFERENCES companies(companyID)
);




-- =========================================
-- STATIONS TABLE
-- =========================================

CREATE TABLE IF NOT EXISTS stations (
    stationID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stationName VARCHAR(50),
    location VARCHAR(255),
    dockCapacity INT
);


CREATE TABLE docks (
    dockID SERIAL PRIMARY KEY,
    stationID INT NOT NULL,
    bikeID INT UNIQUE,
    status VARCHAR(50) NOT NULL DEFAULT 'available'
        CHECK (status IN ('available', 'occupied', 'out_of_service')),

    CONSTRAINT fk_dock_station
        FOREIGN KEY (stationID) REFERENCES stations(stationID)
        ON DELETE CASCADE,

    CONSTRAINT fk_dock_bike
        FOREIGN KEY (bikeID) REFERENCES bikes(bikeID)
        ON DELETE SET NULL


);
